export function isBreedUnlocked(breedId, saveState) {
  if (breedId === 'pomeranian') return true;
  if (saveState?.unlockedBreeds?.includes(breedId)) return true;
  const def = BREEDS.find((b) => b.id === breedId);
  if (!def) return false;
  return Boolean(def.unlockStage && (saveState?.maxUnlockedUnit || 1) >= def.unlockStage);
}

