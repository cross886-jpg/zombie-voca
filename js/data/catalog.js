/**
 * 보유 또는 스테이지 해금된 코스튬 전체의 도감 누적 보너스 계산
 * @param {string[]} ownedCostumeIds
 * @param {number} maxUnlockedUnit
 * @returns {{ atkBonus: number, hpBonus: number }}
 */
export function getCostumeCollectionBonus(ownedCostumeIds = [], maxUnlockedUnit = 1) {
  const ownedSet = new Set(ownedCostumeIds);
  let atkBonus = 0;
  let hpBonus = 0;

  for (const item of COSTUMES) {
    if (ownedSet.has(item.id) || (item.unlockStage && maxUnlockedUnit >= item.unlockStage)) {
      atkBonus += item.atkBonus || 0;
      hpBonus += item.hpBonus || 0;
    }
  }
  return { atkBonus, hpBonus };
}

