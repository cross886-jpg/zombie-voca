export function isCompanionUnlocked(compId, saveState) {
  if (saveState?.companions?.unlocked?.includes(compId)) return true;
  const def = COMPANIONS.find((c) => c.id === compId);
  if (!def) return false;
  return Boolean(def.unlockStage && (saveState?.maxUnlockedUnit || 1) >= def.unlockStage);
}


